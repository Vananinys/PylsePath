-- Run as project administrator. All data mutations are rolled back.
begin;
do $$
declare users uuid[]; a uuid; b uuid; outsider uuid; club uuid:=gen_random_uuid();
 open_club uuid:=gen_random_uuid(); message uuid:=gen_random_uuid(); event uuid:=gen_random_uuid();
 snap jsonb; code text; old_code text; denied boolean; room jsonb; room_id uuid;
begin
 select array_agg(id) into users from (select id from auth.users order by created_at limit 3) s;
 if cardinality(users)<3 then raise exception 'Need three existing accounts'; end if;
 a:=users[1];b:=users[2];outsider:=users[3];
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 snap:=public.club_action('create',null,jsonb_build_object('id',club,'name','Transactional QA club','description','temporary','is_open',false));
 assert snap->>'role'='owner'; code:=snap->>'invite_code'; assert length(code)=32;
 snap:=public.club_action('create',null,jsonb_build_object('id',club,'name','Transactional QA club','is_open',false));
 assert jsonb_array_length(snap->'members')=1;
 perform public.club_action('message',club,jsonb_build_object('id',message,'body','retained history'));
 snap:=public.club_action('message',club,jsonb_build_object('id',message,'body','retained history'));
 assert jsonb_array_length(snap->'messages')=1;
 snap:=public.club_action('event_create',club,jsonb_build_object('id',event,'title','Test club event','starts_at',now()+interval '1 day'));
 assert jsonb_array_length(snap->'events')=1;
 denied:=false;
 begin perform public.club_action('leave',club); exception when others then denied:=sqlerrm like '%CLUB_TRANSFER_FIRST%'; end;
 assert denied,'owner cannot orphan club';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
 snap:=public.club_action('home');
 assert not exists(select 1 from jsonb_array_elements(snap) z where z->>'id'=club::text),'private club not discoverable';
 denied:=false;begin perform public.club_action('snapshot',club);exception when others then denied:=sqlerrm like '%CLUB_MEMBER_REQUIRED%';end;
 assert denied,'outsider cannot read chat';
 denied:=false;begin perform public.club_action('join',club);exception when others then denied:=sqlerrm like '%CLUB_INVITE_REQUIRED%';end;
 assert denied,'private club requires code';
 denied:=false;begin perform count(*) from public.rider_clubs;exception when insufficient_privilege then denied:=true;end;
 assert denied,'raw table inaccessible';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 snap:=public.club_action('join_code',null,jsonb_build_object('code',code));
 assert snap->>'role'='member' and snap->>'invite_code' is null;
 assert jsonb_array_length(snap->'messages')=1;
 denied:=false;begin perform public.club_action('role',club,jsonb_build_object('user_id',b,'role','admin'));exception when others then denied:=true;end;
 assert denied,'cannot self promote';
 snap:=public.club_action('event_attend',club,jsonb_build_object('id',event,'attending',true));
 assert jsonb_array_length(snap->'events'->0->'attendees')=1;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 snap:=public.club_action('role',club,jsonb_build_object('user_id',b,'role','admin'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 snap:=public.club_action('join_code',null,jsonb_build_object('code',code));
 assert snap->>'role'='admin','repeat join retains role';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 old_code:=code;snap:=public.club_action('rotate_code',club);code:=snap->>'invite_code';assert code<>old_code;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
 denied:=false;begin perform public.club_action('join_code',null,jsonb_build_object('code',old_code));exception when others then denied:=sqlerrm like '%CLUB_CODE_INVALID%';end;
 assert denied,'old invitation revoked';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 snap:=public.club_action('transfer',club,jsonb_build_object('user_id',b));assert snap->>'owner_id'=b::text;
 perform public.club_action('leave',club);
 denied:=false;begin perform public.club_action('messages',club);exception when others then denied:=sqlerrm like '%CLUB_MEMBER_REQUIRED%';end;
 assert denied,'departed member cannot read history';
 snap:=public.club_action('create',null,jsonb_build_object('id',open_club,'name','Open QA club','is_open',true));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
 snap:=public.club_action('snapshot',open_club);assert snap->>'member'='false' and not snap?'messages';
 snap:=public.club_action('join',open_club);assert snap->>'member'='true';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 snap:=public.club_action('event_cancel',club,jsonb_build_object('id',event));assert snap->'events'->0->>'cancelled_at' is not null;
 -- Use pre-existing group API only within this rollback transaction.
 room:=public.group_room_action('create',null,true,'Club QA workout',null);
 room_id:=(room->>'id')::uuid;
 message:=gen_random_uuid();
 snap:=public.club_action('share_ride',club,jsonb_build_object('id',message));
 assert exists(select 1 from jsonb_array_elements(snap->'messages') z where z->>'ride_id'=room_id::text);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
 denied:=false;begin perform public.club_action('join_ride',club,jsonb_build_object('id',message,'replace',true));exception when others then denied:=sqlerrm like '%CLUB_MEMBER_REQUIRED%';end;
 assert denied,'outsider cannot use club ride invitation';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform public.club_action('join_code',null,jsonb_build_object('code',code));
 snap:=public.club_action('join_ride',club,jsonb_build_object('id',message,'replace',true));assert snap->>'room_id'=room_id::text;
 execute 'reset role';
 assert not has_function_privilege('anon','public.club_action(text,uuid,jsonb)','execute');
end $$;
rollback;
select 'Club authorization, roles, private data, idempotency, events, and ride invitation checks passed; all changes rolled back' as result;
